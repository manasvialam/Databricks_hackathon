const TABLE: Record<Lang, Partial<Messages>> = { en, hi, ta, te, ml };

export function t(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  let s = (TABLE[lang][key] ?? en[key]) as string;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Keys that fall back to English in each language, so reviewers can see exactly what is missing. */
