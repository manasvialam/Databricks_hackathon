"""Builds Person_1/output/data_quality_report.md from run_stats.json + the output files.
Every number in the report is read from the run, not typed by hand.  Run after build_fac_base.py."""
import json
from pathlib import Path

import pandas as pd

OUT = Path(__file__).resolve().parent / "output"
S = json.loads((OUT / "run_stats.json").read_text())
d = pd.read_parquet(OUT / "fac_base.parquet")
nf = S["nfhs"]
num = S["numeric"]
sp = S["specialties"]
lc = {r["column"]: r for r in S["list_cleaning"]}
V = json.loads((OUT / "verification_stats.json").read_text())
f = lambda n: f"{n:,}"


def table(rows, header):
    out = ["", "| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


R = []
w = R.append
w("# Data Quality Report: Section 1 (Person 1: Base table)\n")
w("*Generated by `Person_1/make_report.py` from `run_stats.json` and `verification_stats.json`. Every number below comes from the pipeline run. Run order: `build_fac_base.py` → `verify_external.py` → `make_report.py`.*\n")
w("## Summary\n")
w(table([
    ["Physical lines in facilities.csv (excluding header)", f(S["raw_physical_lines"] - 1)],
    ["Rows parsed (with the correct escape setting)", f(S["raw_rows_parsed"])],
    ["Fragment rows → quarantine file", f(S["fragment_rows"])],
    ["Real records", f(S["real_record_rows"])],
    ["Broken (truncated) records repaired", f"{S['truncated_repaired']} of {S['truncated_records']}"],
    ["Exact duplicate rows dropped", f(S["rows_dropped_as_duplicates"])],
    ["**Facilities in `fac_base`**", f"**{f(S['facilities_final'])}**"],
    ["Columns in `fac_base`", f"{d.shape[1]} ({S['output_columns']['total']} from cleaning + {d.shape[1] - S['output_columns']['total']} from verification)"],
    ["Facilities with at least one plain-language reason", f(S["rows_with_any_reason"])],
    ["NFHS districts parsed", f"{nf['rows']} × {nf['indicators']} indicators"],
], ["Step", "Count"]))

w("\n## 1. Loading the file (A1)\n")
w(f"- The file escapes quotes with a backslash (`\\\"`: {f(S['raw_escaped_quotes'])} times) instead of doubling them (`\"\"`: {S['raw_doubled_quotes']} times).")
w(f"- A default `pd.read_csv` **{S['naive_read_csv'].strip()}**")
w(f"- With `escapechar='\\\\'` it parses into {f(S['raw_rows_parsed'])} rows, one per physical line.")

w("\n## 2. Fragment rows and broken records (A2, A3)\n")
w(f"- {S['fragment_rows']} rows are not records: their `unique_id` is a piece of text, not an ID. "
  f"They are pieces of {S['truncated_records']} real records whose description contained line breaks.")
w(f"- All {S['fragments_belonging_to_truncated']} fragments belong to those {S['truncated_records']} records. "
  f"Each record's first line ends right after `description`, and its other **{S['n_post_description_cols']} columns** sit on its last fragment line.")
w(f"- **Repaired: {S['truncated_repaired']} of {S['truncated_records']}.** The description text from the middle lines is re-joined, and the {S['n_post_description_cols']} columns come from the last line.")
w(table([[m, n] for m, n in S["repair_methods"]], ["How the last line was decoded", "Records"]))
w("- `pass1+quote`: the last line is normal CSV once the description's opening quote is added back.")
w("- The 2 harder records (*Jayapriya Eye Hospital, Hubli*; *Royals Dental Care, Haldwani*) had their tail escaped twice and their lists split into one field per item. The pieces were re-joined into lists. Their GeoJSON `coordinates` was rebuilt from latitude/longitude.")
w("- Check on every repaired record: specialties parse as a list, source_urls parse as a list, latitude and longitude are numbers, and cluster_id is present.")
rep = d[d.flag_repaired_record]
w(f"- Result: {rep.specialties.notna().sum()}/30 have specialties, {rep.latitude.between(6, 37.6).sum()}/30 have coordinates inside India, "
  f"{rep.source_urls.notna().sum()}/30 have source URLs.")
w("- The first, cut-off description is kept in `raw_description_truncated`. Each repaired row has `flag_repaired_record = True`.")
w(f"- `facilities_quarantine.csv` keeps all {S['output_quarantine_rows']} fragments, each with the record it belongs to and its original line number.")

w("\n## 3. Exact duplicates (A4)\n")
w(f"- {S['duplicate_unique_ids']} `unique_id`s appear twice. Byte-identical: **{S['duplicate_rows_identical']}**, so one copy of each was dropped.")
w(f"- Facilities affected: {', '.join(S['duplicate_names'])}.")

w("\n## 4. Missing values and lists (A5, G2, G4)\n")
mt = S["missing_tokens_total"]
w(f"- Missing appears in three forms: empty string ({f(mt['empty string'])} cells), `null` ({f(mt[chr(39)+'null'+chr(39)])} cells) "
  f"and `NULL` ({mt[chr(39)+'NULL'+chr(39)]} cell). All became real missing values.")
w("- All 10 list columns were parsed from JSON. Blank items were dropped and repeats removed (first occurrence kept). A list that ends up empty becomes **missing**, so *no data* is never counted as *has data*.\n")
w(table([[c, f(r["items_before"]), f(r["blank_items"]), f(r["items_after"]), f(r["lists_at_50_cap"]),
          f(r["empty_or_blank_only_lists_to_missing"]), f"{f(r['facilities_now_missing'])} ({r['facilities_now_missing']/S['facilities_final']*100:.1f}%)"]
         for c, r in lc.items()],
        ["List", "Items before", "Blank items", "Items after", "Lists at 50-item cap", "Empty/blank-only → missing", "Facilities missing"]))
w(f"\n- JSON parse failures: {sum(r['json_parse_failures'] for r in lc.values())}.")
w(f"- **`flag_list_truncated`** = any of specialties/procedure/equipment/capability had exactly 50 items in the raw data: **{f(S['flag_list_truncated'])} facilities**. "
  "It has to be computed *before* removing repeats, or the cap disappears. The raw lengths are kept as `rawlen_<col>`.")

w("\n## 5. Dead / redundant columns (A6)\n")
dc = S["dead_columns"]
rows = []
for c, v in dc.items():
    extra = ", ".join(f"{k}={v[k]}" for k in v if k not in ("non_null", "distinct_values"))
    rows.append([c, f(v["non_null"]), v["distinct_values"], extra])
w(table(rows, ["Column", "Non-missing", "Distinct values", "Check"]))
w(f"\n- These {len(dc)} columns were renamed to `raw_<col>`. They're kept, but not part of the cleaned table.")

w("\n## 6. Types and categories (A7)\n")
tf = S["type_conversion_failures"]
w(f"- Numbers: 0 conversion failures for all {len([k for k in tf if not k.startswith(('recency', 'post_metrics_most'))])} numeric columns. Doctors, beds and year are whole numbers (nullable integers).")
ud = S["unparsed_date_values"]
w(f"- Dates: only exact `YYYY-MM-DD` values are converted. {tf['recency_of_page_update']} page-update values and "
  f"{tf['post_metrics_most_recent_social_media_post_date']} last-post values are text with no reliable date "
  f"(e.g. {', '.join(repr(x) for x in (ud['recency_of_page_update'][:3] + ud['post_metrics_most_recent_social_media_post_date'][:3]))}). "
  "They are left missing and kept in `raw_`, so no year is invented.")
w(f"- `facilityTypeId`: farmacy ({S['facilityTypeId_before'].get('farmacy', 0)}) → pharmacy. Now: {S['facilityTypeId_after']}.")
w(f"- `operatorTypeId`: government ({S['operatorTypeId_before'].get('government', 0)}) → public. Now: {S['operatorTypeId_after']}.")

w("\n## 7. Specialties (G5, G6)\n")
w(f"- Distinct specialty strings: **{f(sp['distinct_before'])} → {f(sp['distinct_after'])}**. {sp['spellings_merged']} spellings were merged into one version each, "
  f"changing {sp['facility_mentions_changed']} facility mentions.")
w("- Rule: two strings are the same specialty if they match after ignoring case, spaces and punctuation. The code-style spelling wins (e.g. `cardiology`); otherwise the most common spelling.")
w("- Examples: " + "; ".join(f"`{a}` → `{b}`" for a, b in sp["examples_merged"][:10]) + ".")
w(f"- After cleaning: {f(sp['code_like_after'])} code-style strings and {sp['not_code_like_after']} free-text ones (top: "
  + ", ".join(f"`{s}` ({n})" for s, n in sp["top_not_code_like"][:6]) + ").")
w(f"- `internalMedicine` is on **{sp['internalMedicine_share_pct']}%** of facilities. `specialties_informative` = the specialty list without it.")
w(f"- {f(sp['used_by_one_facility_after'])} specialties are used by only one facility. They are **kept** and listed in `specialties_rare`, "
  "because many are meaningful (e.g. " + ", ".join(f"`{x}`" for x in sp["examples_rare_kept"][4:9]) + ").")

w("\n## 8. Doctors, beds, founding year (F1–F7): team decision, keep large values\n")
w("Team decision (21 Nov): large doctor/bed counts and old founding years are **kept**. They go into a top "
  "\"very large / super-speciality scale\" band and are flagged for verification (see section 12). Only values that cannot be real are cleared.")
nd, cp, yr = num["numberDoctors"], num["capacity"], num["yearEstablished"]
w(table([
    ["numberDoctors", f(nd["present"]), f"0 → missing: {nd['zero_to_missing']}",
     f">1,000 kept + `flag_doctors_extreme`: {nd['over_1000_kept_flagged']}; clinic/dentist/doctor/pharmacy >50: {nd['small_type_over_50_flagged']}"],
    ["capacity (beds)", f(cp["present"]), f"0 → missing: {cp['zero_to_missing']}",
     f">3,000 kept + `flag_capacity_extreme`: {cp['over_3000_kept_flagged']}; small type >200 beds: {cp['small_type_over_200_flagged']}"],
    ["yearEstablished", f(yr["present"]), f"not a year (<1500) → missing: {yr['not_a_year_to_missing']}",
     f"before 1800 kept + `flag_year_very_old`: {yr['before_1800_kept_flagged']}"],
], ["Field", "Present (raw)", "Cleared (original kept in raw_)", "Kept but flagged"]))
w("\n**Doctor counts above 1,000 (kept, flagged):** " + "; ".join(f"{n} ({c}) {v}" for n, c, t, v in nd["over_1000_rows"]) + ".")
w("\n**Bed counts above 3,000 (kept, flagged):** " + "; ".join(f"{n} ({c}) {v}" for n, c, v in cp["over_3000_rows"]) + ".")
w("\n**Years cleared (not a year):** " + "; ".join(f"{n[:45]} ({c}) {v}" for n, c, v in yr["not_a_year_rows"]) + ".")
w("\n**Years before 1800 (kept, flagged):** " + "; ".join(f"{n} ({c}) {v}" for n, c, v in yr["before_1800_rows"]) + ".")
w(f"\n- `flag_one_doctor_many_beds` (1 doctor and ≥100 beds): **{num['one_doctor_many_beds']}**. `numberDoctors = 1` is on {f(num['numberDoctors_eq_1'])} facilities, "
  "most likely meaning one named doctor was found, not the staff size.")
w(f"- Value heaping: {num['capacity_multiple_of_10_pct']}% of bed counts ≥10 are multiples of 10, so beds are estimates. Two bands were added:")
w(table([[k, f(v)] for k, v in num["size_band"].items()], ["size_band", "Facilities"]))
w(table([[k, f(v)] for k, v in num["doctor_band"].items()], ["doctor_band", "Facilities"]))
w(f"- Still missing after cleaning (**not filled in**): capacity {num['missing_after_cleaning_pct']['capacity']}%, "
  f"doctors {num['missing_after_cleaning_pct']['numberDoctors']}%, year {num['missing_after_cleaning_pct']['yearEstablished']}%. "
  f"Clinics without a bed count: {num['clinic_capacity_missing_pct']}%.")
dn = S["display_name"]
w(f"\n### display_name\n- {dn['names_with_pin']} names contain a PIN code (an address glued onto the name). For these, `display_name` keeps only the facility name; `name` is unchanged. {dn['shortened']} were shortened. Examples:")
w(table([[a[:90], b] for a, b in dn["examples"][:10]], ["name (original)", "display_name"]))

w("\n## 9. Near-duplicates (I1, I2)\n")
dg = S["duplicate_groups"]
w(f"- Rules: same name (lower-case, letters/digits only) **and** same city → {dg['by_rule']['name+city']['groups']} groups; "
  f"same name **and** same 6-digit PIN → {dg['by_rule']['name+PIN']['groups']} groups. Combined: **{dg['groups_total']} groups, {dg['rows_in_groups']} rows**.")
w(f"- Confidence: **likely** = same PIN or within 2 km ({dg['confidence'].get('likely', 0)} groups); **possible** = same name and city but a different PIN and location "
  f"({dg['confidence'].get('possible', 0)} groups, may be different branches).")
w(f"- Only *likely* groups get `is_primary = False` on the less complete record ({dg['non_primary_rows']} rows). Nothing is deleted. All {dg['rows_in_groups']} rows have `flag_possible_duplicate`.")
w(table([e[:5] + [e[7]] for e in dg["examples"]], ["dup_group_id", "confidence", "name", "city", "PIN", "is_primary"]))

w("\n## 10. NFHS-5 (J5)\n")
w(table([
    ["Districts × indicators", f"{nf['rows']} × {nf['indicators']} ({f(nf['cells'])} cells)"],
    ["`*` suppressed (<25 cases) → missing", f(nf["suppressed_star_to_missing"])],
    ["`(x)` low reliability (25–49 cases) → value kept + `lowrel_<col>=True`", f(nf["low_reliability_parenthesised"])],
    ["Cells that could not be parsed", nf["unparsed_cells"]],
    ["State names fixed to India Post spelling", "; ".join(f"{a} → {b}" for a, b in nf["states_fixed"].items())],
    ["States not matching India Post after fix", nf["states_not_matching_india_post"] or "none"],
    ["District names that occur in 2+ states", ", ".join(nf["district_names_in_multiple_states"])],
    ["`join_key` (state + district) unique", nf["join_key_unique"]],
], ["Item", "Result"]))

w("\n## 11. Flags in `fac_base`\n")
w(table([[k, f(v)] for k, v in S["flag_counts"].items()], ["Flag", "Facilities"]))

wm, ad, wdx = V["wikidata_match"], V["address"], V["wikidata"]
w("\n## 12. Verification against real outside data\n")
w("Sources: **India Post PIN directory** (official, in the repo); **Wikidata** (independent, downloaded 21 Nov 2026: "
  f"{f(wdx['items'])} Indian hospitals and medical schools, {f(wdx['with_inception'])} with a founding date, {wdx['with_beds']} with a bed count, "
  f"{wdx['with_en_wikipedia']} with an English Wikipedia article); **web search** for the extreme values; and the facility's **own text** "
  "(the same source, so it only shows consistency).")
w("\n### 12a. Matching facilities to Wikidata")
w(table([[k, f(v)] for k, v in wm["by_method"].items()], ["Match rule", "Facilities"]))
w(f"\n- **{wm['matched_facilities']} facilities matched** (median distance {wm['distance_km_median']} km). {wm['dropped_as_second_claim_on_same_item']} weaker second claims on the same Wikidata item were dropped.")
w("- Rules: name similarity (generic words, state names and the facility's own city removed; a specialty-word mismatch such as Dental vs not is penalised) AND within 15 km of the record's coordinates or its PIN centre. The record's own `officialWebsite` domain can lower the name threshold.")
w("- **Manual audit:** about 310 matches in 7 random samples were reviewed by eye while building the rules. Each error found led to a rule change. With the final rules, a general sample of 50 was 50/50 correct and a sample of 30 medical-school matches was 29/30 (the miss: SVIMS Tirupati matched to Sri Venkateswara Medical College). Four matches found wrong or doubtful in the audit are rejected in the code (`REJECTED_MATCHES`): Krishna Clinic → Krishna Heart Institute, Regional Mental Hospital Nagpur → Yerwada Mental Hospital, SVIMS Tirupati → Sri Venkateswara Medical College, Max Centre for Liver & Biliary Sciences → ILBS.")
w("\n### 12b. Address check (`address_check`, `address_evidence`)")
w(table([[k, f(v)] for k, v in ad["address_check"].items()], ["address_check", "Facilities"]))
w(f"\n- PIN found in India Post: {f(ad['pin_valid'])}. The city appears in the PIN's district or post-office names: {f(ad['city_matches_pin'].get('True', 0))}; it does not: {f(ad['city_matches_pin'].get('False', 0))}.")
w("- **verified** = valid PIN, state agrees, coordinates within 10 km of the PIN centre, and the city matches the PIN (or Wikidata confirms the location). "
  "**consistent** = within 25 km. **conflict** = state contradicts the PIN (excluding the AP/Telangana split) or coordinates more than 100 km from the PIN.")
w("- Limit: this checks that the PIN, city, state and coordinates agree with official data. It cannot confirm the street or building.")
w("\n### 12c. Founding year (`year_check`, `year_evidence`)")
w(table([[k, f(v)] for k, v in V["year_check"].items()], ["year_check", "Facilities"]))
w("\n- Only **Wikidata** and **web** results are independent. \"consistent with own text\" means the record's description says the same year (e.g. \"established in 1987\"), so it shows consistency, not proof.")
w("\n### 12d. Beds and doctors (`capacity_check`, `doctors_check`)")
w(table([[k, f(v)] for k, v in V["capacity_check"].items()], ["capacity_check", "Facilities"]))
w(table([[k, f(v)] for k, v in V["doctors_check"].items()], ["doctors_check", "Facilities"]))
mw = pd.read_csv(OUT.parent / "external" / "manual_web_checks.csv")
w("\n### 12e. Web checks of every extreme value")
w(table([[r.name[:45], r.field, r.record_value, r.verdict, r.finding[:110]] for r in mw.itertuples()],
        ["Facility", "Field", "Record", "Verdict", "What the sources say"]))
w("\nSource URLs for each row are in `external/manual_web_checks.csv` and in the `web_check_sources` column.")
vc, vd = V["value_corrections"], V["value_disputes"]
corr = pd.read_csv(OUT / "value_corrections.csv"); disp = pd.read_csv(OUT / "value_disputes.csv")
w("\n### 12f. Using real values instead of the dataset's (`<col>_source`, `<col>_alt_value`)")
w("Rules (the dataset's value always stays in `raw_<col>`):")
w("1. **Web check with a specific value** → it replaces the record value.")
w("2. **Record has no value, Wikidata has one** → filled from Wikidata.")
w("3. **Record and Wikidata disagree, not web-checked** → the record value stays, Wikidata's value goes in `<col>_alt_value`, and the check says *disputed*.")
w("Rule 3 exists because of the web checks themselves. Of 8 year disagreements checked on the web, Wikidata was right in 1 (MIOT), "
  "the record in 3 (RIMS 1960, Goa Medical College 1842, Mohak 2010), neither in 2 (Oyster & Pearl → 2008, IMS & SUM → 2007) "
  "and 2 are unresolved. Wikidata's 'inception' is sometimes a renaming or upgrade date, so copying it blindly would add new errors.")
w(f"\n- **Replaced after a web check: {vc['replaced']}** · **filled from Wikidata: {vc['filled']}** · **disputed (both values shown): {vd['total']}** ({vd['by_field']})")
w(table([[r.field, r.name[:45], int(r.record_value), int(r.new_value), r.source] for r in corr[corr.record_value.notna()].itertuples()],
        ["Field", "Facility", "Record value", "Real value", "Source"]))
w("\nAll fills and disputes are listed in `value_corrections.csv` and `value_disputes.csv`.")

rc = V["recognition"]
w("\n### 12g. Recognition (`recognition_tier`, `recognition_score`, `recognition_evidence`)")
w("This is **not** a quality or patient-review score: no lawful, free review source covers 10,000 Indian facilities. It counts verifiable signs of standing:")
w(table([["English Wikipedia article (via Wikidata match)", "+3"], ["Listed on Wikidata only", "+1"],
         ["NABH / JCI accreditation claimed in the record", "+2"], ["NABH entry-level / pre-accreditation or NABL claimed", "+1"],
         ["Teaching hospital / medical college / academic affiliation", "+2"],
         ["Operating ≥ 50 years (year confirmed or consistent)", "+2"], ["Operating 25–49 years", "+1"]], ["Signal", "Points"]))
w("\nTiers: high ≥ 5, moderate 3–4, some 1–2, *no evidence found* 0. *No evidence found* means **unknown**, not bad.")
w(table([[k, f(v)] for k, v in rc["tier"].items()], ["recognition_tier", "Facilities"]))

